"""Build the figures+tables Word file for FitMeasureAI, reusing the thesis template.

The source .docx is opened as a template so styles.xml / theme / numbering carry over
verbatim (Normal = Times New Roman 14 pt, 1.5 line, first-line indent 1.25 cm,
justified; headings "Heading 1..3"; tables "Table Grid1"). Its body is then emptied and
refilled, so anything here can be pasted into the thesis without restyling.
"""
from __future__ import annotations

import re
from pathlib import Path

import docx
from docx.enum.table import WD_TABLE_ALIGNMENT
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt

REPO = Path(__file__).resolve().parent.parent.parent
