_ap.add_argument("--template", required=True, help="the thesis .docx, used for styles only")
_ap.add_argument("--out", default="FitMeasureAI_рисунки_і_таблиці.docx")
_args = _ap.parse_args()
TPL = Path(_args.template)
OUT = Path(_args.out)

CONTENT_W = Cm(16.5)  # page content width is 17 cm; keep a small safety margin

doc = docx.Document(str(TPL))
body = doc.element.body
for child in list(body):
    if not child.tag.endswith("}sectPr"):
        body.remove(child)


def para(text="", style=None, *, center=False, indent=True, bold=False,
         italic=False, size=None, space_before=None, space_after=None):
    p = doc.add_paragraph()
    if style:
        p.style = doc.styles[style]
    if center:
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        p.paragraph_format.first_line_indent = Cm(0)
    elif not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    if space_before is not None:
        p.paragraph_format.space_before = Pt(space_before)
    if space_after is not None:
        p.paragraph_format.space_after = Pt(space_after)
    if text:
        # **bold** markers inside the source strings
        for i, chunk in enumerate(re.split(r"\*\*(.+?)\*\*", text)):
            if not chunk:
                continue
            run = p.add_run(chunk)
            # Only ever set these to True: assigning False writes an explicit
            # <w:b w:val="0"/> on the run, which overrides the bold that the
            # Heading styles carry and silently un-bolds every heading.
            if bold or i % 2 == 1:
                run.bold = True
            if italic:
                run.italic = True
            if size:
                run.font.size = Pt(size)
    return p


def figure(png: str, caption: str, width_cm: float = 16.0, note: str | None = None):
    p = doc.add_paragraph()
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.space_before = Pt(6)
    p.add_run().add_picture(str(FIGS / png), width=Cm(width_cm))
    para(caption, center=True, space_after=6)
    if note:
        para(note, center=False, indent=False, size=12, space_after=10)


def table(head: list[str], rows: list[list[str]], widths: list[float], head_size: float = 12):
    t = doc.add_table(rows=1, cols=len(head))
    t.style = doc.styles["Table Grid1"]
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    t.autofit = False
    for i, w in enumerate(widths):
        for cell in t.columns[i].cells:
            cell.width = Cm(w)
    for i, h in enumerate(head):
        c = t.rows[0].cells[i]
        c.text = ""
        pp = c.paragraphs[0]
        pp.alignment = WD_ALIGN_PARAGRAPH.CENTER
        pp.paragraph_format.first_line_indent = Cm(0)
        pp.paragraph_format.space_after = Pt(0)
        r = pp.add_run(h)
        r.bold = True
        r.font.size = Pt(head_size)
    for row in rows:
        cells = t.add_row().cells
        for i, val in enumerate(row):
            cells[i].width = Cm(widths[i])
            pp = cells[i].paragraphs[0]
            pp.alignment = WD_ALIGN_PARAGRAPH.CENTER if i else WD_ALIGN_PARAGRAPH.LEFT
            pp.paragraph_format.first_line_indent = Cm(0)
            pp.paragraph_format.space_after = Pt(0)
            for j, chunk in enumerate(re.split(r"\*\*(.+?)\*\*", val)):
                if not chunk:
                    continue
                r = pp.add_run(chunk)
                if j % 2 == 1:
                    r.bold = True
                r.font.size = Pt(12)
    para(space_after=6)
    return t


